#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""从 shared/test-tracks.json 生成引擎与 App 两侧的合成测试曲名单。

引擎按它挡打卡和网页中继的「正在播放」,App 按它挡 Discord「正在听」(12 章决策 98、99)。两边各写一份,
新加一个测试歌手就会只有一边认得,所以名单只放在那份 JSON 里,这里生成两个文件:

- lyrimuse-engine/testtracks_generated.go                     名单(引擎)
- lyrimuse/Sources/LyrimuseCore/Models/TestTracks+Generated.swift  名单(App)

比对逻辑手写在 scrobblehold.go `isTestTrack` / ScrobbleHold.swift `isTestTrack`;JSON 里的 match / keep / match_untagged /
keep_tracks 例句由两侧测试在测试时直接读这份 JSON 去跑,不生成。
"""
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "shared" / "test-tracks.json"

GO_FILE = "lyrimuse-engine/testtracks_generated.go"
CORE_SWIFT = "lyrimuse/Sources/LyrimuseCore/Models/TestTracks+Generated.swift"

BANNER_SWIFT = (
    "// 由 scripts/gen-test-tracks.py 从 shared/test-tracks.json 生成,请勿手改。\n"
    "// 改名单:改那份 JSON → 跑 `python3 scripts/gen-test-tracks.py`。CI 跑 `--check` 对账,手改这里会红。\n"
)
BANNER_GO = (
    "// Code generated by scripts/gen-test-tracks.py from shared/test-tracks.json; DO NOT EDIT.\n"
    "//\n"
    "// 改名单:改那份 JSON → 跑 `python3 scripts/gen-test-tracks.py`。CI 跑 `--check` 对账,手改这里会红。\n"
)


def fail(msg):
    sys.exit("shared/test-tracks.json: " + msg)


def load():
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    out = {}
    for key in ("artist_prefixes", "artists", "untagged_titles", "match", "keep", "match_untagged"):
        values = spec.get(key)
        if not isinstance(values, list) or not all(isinstance(v, str) for v in values):
            fail(f"{key} 必须是字符串数组")
        out[key] = values
    for key in ("artist_prefixes", "artists", "untagged_titles"):
        seen = set()
        for v in out[key]:
            norm = v.strip().lower()
            if not norm:
                fail(f"{key} 里有空串")
            if norm in seen:
                fail(f"{key} 重复: {v}")
            seen.add(norm)
    tracks = spec.get("keep_tracks")
    if not isinstance(tracks, list) or not all(
            isinstance(t, dict) and set(t) == {"artist", "title"} and all(isinstance(v, str) for v in t.values()) for t in tracks):
        fail("keep_tracks 必须是 {artist, title} 字符串对象数组")
    out["keep_tracks"] = tracks
    if not out["match"] or not out["keep"] or not out["match_untagged"] or not tracks:
        fail("match、keep、match_untagged、keep_tracks 各至少一句")
    return out


def gofmt(text):
    """过一遍 gofmt:CI 第一步就是 gofmt -l。--check 与写盘走同一条路径。"""
    exe = shutil.which("gofmt")
    if not exe:
        print("  ! 没找到 gofmt,Go 生成物未格式化(CI 的 gofmt 检查会红)")
        return text
    done = subprocess.run([exe], input=text, capture_output=True, text=True)
    if done.returncode != 0:
        sys.exit("gofmt 失败:\n" + done.stderr)
    return done.stdout


def quote(s):
    """Go 与 Swift 的普通字符串字面量在这几个转义上写法相同。"""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def render_go(spec):
    lines = [BANNER_GO, "\npackage main\n\n"]
    lines.append("var testTrackArtistPrefixes = []string{\n")
    lines += ["\t%s,\n" % quote(v) for v in spec["artist_prefixes"]]
    lines.append("}\n\nvar testTrackArtists = []string{\n")
    lines += ["\t%s,\n" % quote(v) for v in spec["artists"]]
    lines.append("}\n\nvar testTrackUntaggedTitles = []string{\n")
    lines += ["\t%s,\n" % quote(v) for v in spec["untagged_titles"]]
    lines.append("}\n")
    return "".join(lines)


def render_core_swift(spec):
    lines = [BANNER_SWIFT, "\nextension ScrobbleHold {\n", "    public static let testArtistPrefixes: [String] = [\n"]
    lines += ["        %s,\n" % quote(v) for v in spec["artist_prefixes"]]
    lines.append("    ]\n\n    public static let testArtists: [String] = [\n")
    lines += ["        %s,\n" % quote(v) for v in spec["artists"]]
    lines.append("    ]\n\n    public static let testUntaggedTitles: [String] = [\n")
    lines += ["        %s,\n" % quote(v) for v in spec["untagged_titles"]]
    lines.append("    ]\n}\n")
    return "".join(lines)


def main():
    check = "--check" in sys.argv[1:]
    spec = load()
    rendered = {GO_FILE: gofmt(render_go(spec)), CORE_SWIFT: render_core_swift(spec)}
    stale = []
    for rel, text in rendered.items():
        path = ROOT / rel
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            print("  = %s" % rel)
            continue
        if check:
            stale.append(rel)
            print("  ✗ %s 与 shared/test-tracks.json 对不上" % rel)
            continue
        path.write_text(text, encoding="utf-8")
        print("  → %s %s" % (rel, "(新建)" if current is None else "(更新)"))
    if check and stale:
        print("\n✗ 生成物过期或被手改。跑 `python3 scripts/gen-test-tracks.py` 重新生成后再提交。")
        return 1
    print("\n✓ %d 个前缀、%d 个整串、%d 个无歌手素材名,两侧生成物与 shared/test-tracks.json 一致"
          % (len(spec["artist_prefixes"]), len(spec["artists"]), len(spec["untagged_titles"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
