/// 歌词里跟标准汉字同形、编码不同的字换回标准字:CJK 部首补充(U+2E80–2EFF)、康熙部首
/// (U+2F00–2FDF)、CJK 兼容表意文字(U+F900–FAFF)。
///
/// 这些字看着跟标准字一样,但署名行规则、繁简转换表、拼音转写都按标准字认:「制作⼈：」不会被当成
/// 署名滤掉,「看⾒」在简体模式下不会转成「看见」,「⻘春」的拼音会粘成一串。见 08 章决策 28。
///
/// 每个字都换成**一个**字,字数不变 —— `[kana:…]` 注音按字数对齐,换完照样对得上。
public enum HanCompatibility {
    /// 换回标准字;不含这三段的字时原样返回(绝大多数歌词走这条)。
    public static func normalized(_ text: String) -> String {
        guard text.unicodeScalars.contains(where: inRange) else { return text }
        var out = String.UnicodeScalarView()
        for scalar in text.unicodeScalars {
            out.append(table[scalar] ?? scalar)
        }
        return String(out)
    }

    private static func inRange(_ scalar: Unicode.Scalar) -> Bool {
        (0x2E80...0x2FDF).contains(scalar.value) || (0xF900...0xFAFF).contains(scalar.value)
    }

    private static let table: [Unicode.Scalar: Unicode.Scalar] = {
        var map: [Unicode.Scalar: Unicode.Scalar] = [:]
        let scalars = Array(pairs.unicodeScalars)
        for i in stride(from: 0, to: scalars.count - 1, by: 2) {
            map[scalars[i]] = scalars[i + 1]
        }
        return map
    }()

