import Foundation

/// 繁简转换之外的**异体字规范化**。
///
/// 为什么需要它:用户 2026-08-22 报「明明开了简体,歌词里还是看到繁体」,实例是周杰伦
/// 《开不了口 (Live)》——ICU 把那首歌 37 种字符全转对了(沒→没、煩→烦、開→开、讓→让…),
/// **只剩「妳」一个字没动,而它出现了 21 次**,整屏都是,看着就是"没转"。
///
/// 根因不是 ICU 有 bug,而是「妳」压根不在繁简转换的范畴里:它是大陆《第一批异体字整理表》
/// 淘汰、港台仍在用的**异体字**,不是「你」的繁体。所以 ICU 的 Traditional-Simplified 不
/// 处理它 —— 换成 OpenCC 也一样,实测 gocc 的 TSCharacters / TWVariantsRev / HKVariantsRev
/// 三张字典里都**没有**「妳」「祂」「牠」的任何条目(全库 grep 过)。这一层只能项目自己补。
///
/// ⚠️ 只在**转简体**方向生效,绝不做反向。简体只有「你」,转繁体时无从判断该写「你」还是
/// 「妳」——那要猜被称呼者的性别,猜错就是改写歌词。同理「他/她/它」也不反推。
///
/// 表的收录标准(宁缺勿滥,每加一个字都要能说清为什么):
///  1. ICU 的 Hant-Hans **确实不转**它(转得动的一律不进表,免得跟 ICU 的上下文判断打架);
///  2. 大陆规范里有明确的取代字;
///  3. 在中文歌词语境里**无歧义** —— 这一条否掉了几个候选:「祇」不收(神祇 vs 只)、
///     「乾」不收(乾坤/乾隆,ICU 已按上下文正确保留)、粤语字「嘅咁哋冇」不收(不是异体,
///     是另一种书面语,转了才是错)。
///
/// 收录的字都在这台机器的真实歌词库(1487 条 enrich 缓存)里核过词频,不是凭空列的。
public enum HanVariants {
    /// 异体 → 大陆规范字。value 必须是单个 Character(逐字替换,不涉及词组上下文)。
    ///
    /// 词频是 2026-08-22 在本机 enrich 缓存上实测的(正文+译文+逐字数据合计):
    ///   妳 149 次 / 13 首、祂 50 次 / 2 首、濛 28 次 / 4 首、牠 2 次 / 1 首、痲 1 次 / 1 首。
    ///
    /// ⚠️ 「濛」是这几个里唯一有残余歧义的:它作人名/地名时不该改(歌词里概率低,而
    /// 「细雨濛濛」→「蒙蒙」才是规范写法)。真撞上误改再把它摘掉即可 —— 摘一个字的代价
    /// 就是删一行,不影响其余。其余四个在任何语境下都是单向取代,没有反例。
    public static let toSimplified: [Character: Character] = [
        "妳": "你",   // 女性第二人称,大陆规范用「你」
        "祂": "他",   // 对神的第三人称
        "牠": "它",   // 对动物的第三人称
        "濛": "蒙",   // 细雨濛濛 → 蒙蒙
        "痲": "麻",   // 痲疹/痲痹 → 麻
        "痺": "痹",   // 同上,痲痺 → 麻痹(这个是写 selftest 时才发现的:我原以为 ICU 会转它)
    ]

    /// 把 ICU 转换的结果再过一遍异体字表。
    ///
    /// 快路径:先扫一遍看有没有命中,没有就原样返回同一个 String —— 绝大多数歌词一个都不
    /// 命中,而这个函数在换歌/改设置时对整份歌词+译文+逐字数据各跑一次,不该无谓地重建字符串。
    public static func normalizeToSimplified(_ text: String) -> String {
        guard text.contains(where: { toSimplified[$0] != nil }) else { return text }
        return String(text.map { toSimplified[$0] ?? $0 })
    }
}
